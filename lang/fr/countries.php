<p>Téhéran est la capitale, tandis qu’Ispahan et Chiraz sont particulièrement célèbres pour leur architecture et leur atmosphère culturelle.</p>
<p class="mt-1"><b>Histoire et culture :</b></p>
<p>Berceau d’une civilisation ancienne, l’Iran a longtemps rayonné dans la littérature, la science, la philosophie et les arts, avec des traditions encore très vivantes.</p>
<p class="mt-1"><b>Économie :</b></p>
<p>L’économie iranienne repose largement sur le pétrole et le gaz, mais aussi sur l’agriculture, l’industrie et différents secteurs technologiques.</p>
<p class="mt-1"><b>Gouvernement et politique :</b></p>
<p>République islamique, l’Iran combine institutions politiques modernes et principes religieux dans un équilibre complexe.</p>
<p class="mt-1"><b>Géographie et climat :</b></p>
<p>Montagnes, déserts, plaines fertiles et villes anciennes composent un territoire contrasté soumis à des climats allant de l’aride au tempéré.</p>
<p class="mt-1"><b>Tourisme et sites emblématiques :</b></p>
<p>Ruines antiques, mosquées majestueuses et jardins historiques permettent d’approcher la richesse patrimoniale du pays.</p>
<p class="mt-1"><b>Cuisine :</b></p>
<p>La cuisine iranienne est connue pour ses épices parfumées, ses kebabs et la finesse de ses préparations héritées de siècles d’échanges culturels.</p>
<p>En résumé, l’Iran demeure un pays de continuité historique et de contraste, où un passé très ancien dialogue sans cesse avec les enjeux du présent.</p>
